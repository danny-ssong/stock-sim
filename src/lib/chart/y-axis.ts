/**
 * 세로로 나란히 놓인 차트들이 공유하는 Y축 폭(px).
 *
 * recharts의 width="auto"는 렌더된 틱 라벨을 실측해 축 폭을 잡는다. 차트마다 라벨
 * 길이가 다르면(가격 차트 "220.00" vs 자산 차트 "1000.00억") 축 폭이 30px 넘게
 * 벌어지고, 그만큼 플롯 영역의 좌측 시작점도 어긋난다. 그러면 x축 틱을 같은 규칙으로
 * 맞춰 놔도(lib/chart/x-axis.ts) 두 차트의 연도 라벨이 세로로 정렬되지 않는다 —
 * 심지어 recharts가 서로 다른 플롯 폭에서 minTickGap을 적용하는 바람에 남는 틱
 * 집합까지 갈렸다(위는 2000·2004·2008…, 아래는 2003·2007·2011…).
 *
 * 그래서 실측을 포기하고 폭을 고정해 공유한다. 정렬은 두 축이 "같은 폭"이기만 하면
 * 되므로, 값 자체는 가장 긴 라벨이 잘리지 않을 만큼만 크면 된다.
 *
 * 96px은 12px 틱 폰트 기준으로 "10000.00억"(1조 원, 약 93px)까지 담는다. 그보다 큰
 * 금액을 다루게 되면 폭을 더 넓히기보다 축 라벨에서 소수점을 걷어내 짧게 만드는 쪽이
 * 먼저다 — 축 눈금에 "1000.00억"의 소수 둘째 자리는 어차피 읽히지 않는다.
 */
export const SHARED_Y_AXIS_WIDTH = 96;
